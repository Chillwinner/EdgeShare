export type I18nKeys = keyof typeof dict.en;

interface I18nContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: I18nKeys) => string;
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'en',
  setLang: () => {},
  t: (k) => dict.en[k],
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('edgeshare_lang') as Lang | null;
    return saved && saved in dict ? saved : 'en';
  });

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem('edgeshare_lang', l);
  };

  const t = (k: I18nKeys): string => dict[lang][k] || dict.en[k];

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
